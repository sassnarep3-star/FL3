#!/usr/bin/env python3
"""Render verified data snapshots (data/*.csv) into ROOT-level static pages.

Pages produced (repo root): data-snapshots.html (hub), data-standings.html,
data-schedule.html, data-injuries.html. These are static hand-generated pages
that coexist with scripts/build_site.py output: the generator's PAGES dict
includes data-snapshots.html in the shared nav, and scripts/check_site.py
validates all four pages. Every table body row carries the official NFL.com
source link it was transcribed from. Blank cells mean the official page showed
no designation. Nothing is inferred.
"""
import csv, html, os
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data"

# Live-site nav (matches scripts/build_site.py PAGES order + this session's pages)
NAV = [
    ("index.html", "Dashboard", "index"),
    ("standings.html", "Standings", "standings"),
    ("data-snapshots.html", "Data snapshots", "data"),
    ("lines.html", "Our Lines", "lines"),
    ("injuries.html", "Injuries", "injuries"),
    ("data-standings.html", "Standings (raw)", "data-standings"),
    ("data-schedule.html", "Schedule (raw)", "data-schedule"),
    ("data-injuries.html", "Injuries (raw)", "data-injuries"),
    ("strategies.html", "Strategies", "strategies"),
    ("correlation.html", "Correlation", "correlation"),
    ("decisions.html", "Decisions", "decisions"),
    ("suggestions.html", "Suggestions", "suggestions"),
    ("flagged.html", "Flagged for Review", "flagged"),
    ("sources.html", "Sources", "sources"),
    ("methodology.html", "Methodology", "methodology"),
    ("spec.html", "Spec", "spec"),
    ("results.html", "Results feed", "results"),
    ("week11.html", "Week 11", "week11"),
    ("availability.html", "Availability", "availability"),
    ("lab.html", "Lab", "lab"),
]

PROVENANCE = (
    '<div class="callout warn"><b>Snapshot provenance.</b> Every value below was transcribed from the official '
    'NFL.com page linked in each row on <b>November 14, 2026 (UTC)</b>. A blank cell means the official page '
    'itself displayed no designation — nothing is inferred or filled in. These are point-in-time transcriptions, '
    'not a live feed; the machine-readable copies live in <code>data/</code> in the repository, and the build '
    'script <code>scripts/build_data.py</code> re-asserts internal consistency on every run. If a value could '
    'not be confirmed from an official source, it is left blank and published on the '
    '<a href="flagged.html">Flagged for Review</a> page.</div>'
)


def page(title, crumb, eyebrow, h1, lead, body, active):
    parts = []
    for href, label, name in NAV:
        if name == active:
            parts.append(f'<a class="on" href="{href}">{html.escape(label)}</a>')
        else:
            parts.append(f'<a href="{href}">{html.escape(label)}</a>')
    nav_html = "".join(parts)
    return f'''<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title} · FL3</title>
<link rel="stylesheet" href="assets/site.css">
</head>
<body>
<header class="top">
  <div class="brand"><span class="mark">FL3</span><span class="sub">NFL Decision System</span></div>
  <nav>{nav_html}</nav>
</header>
<main id="main">
<section class="hero"><div class="eyebrow">{eyebrow}</div><h1>{h1}</h1><p>{lead}</p><div class="crumb-note">Section: {crumb} · static snapshot page · generated by <code>scripts/build_data_pages.py</code></div></section>
{PROVENANCE}
{body}
<footer class="foot"><span>Point-in-time transcriptions · every row links to the official source</span><span><a href="flagged.html">Flagged for Review</a> · <a href="sources.html">Source register</a></span></footer>
</main>
</body>
</html>'''


def table(headers, rows_html, searchable=True, note=""):
    search = '<input class="search" data-table-search placeholder="Search…" aria-label="Search table">' if searchable else ""
    attr = "" if searchable else ""
    nt = f'<span class="small-note">{note}</span>' if note else ""
    return (f'<section class="card"><h2>Table</h2><div class="filter-row">{nt}{search}</div>'
            f'<div class="table-wrap"><table class="data-table"><thead><tr>'
            + "".join(f"<th>{h}</th>" for h in headers)
            + "</tr></thead><tbody>\n" + "\n".join(rows_html) + "\n</tbody></table></div></section>")


def read_csv(name):
    with open(DATA / name, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def esc(v):
    return html.escape(str(v))


# ---------------------------------------------------------------- standings --
st = read_csv("standings_2026_wk9.csv")
rows = []
for i, r in enumerate(st, 1):
    src = f'<a class="src" href="{esc(r["source_url"])}" target="_blank" rel="noopener">NFL.com standings</a>'
    rows.append(
        "<tr><td>{rk}</td><td>{tm}</td><td>{cf}</td><td>{dv}</td><td>{w}</td><td>{l}</td><td>{t}</td><td>{p}</td>"
        "<td>{pf}</td><td>{pa}</td><td>{nt}</td><td>{h}</td><td>{rd}</td><td>{dr}</td><td>{cr}</td><td>{st_}</td><td>{l5}</td><td>{src}</td></tr>".format(
            rk=i, tm=esc(r["name"]), cf=esc(r["conf"]), dv=esc(r["division"]), w=r["w"], l=r["l"], t=r["t"],
            p=esc(r["pct"]), pf=r["pf"], pa=r["pa"], nt=r["net_pts"], h=esc(r["home"]), rd=esc(r["road"]),
            dr=esc(r["div"]), cr=esc(r["conf"]), st_=esc(r["streak"]), l5=esc(r["last5"]), src=src))
standings_body = table(
    ["#", "Team", "Conf", "Div", "W", "L", "T", "PCT", "PF", "PA", "Net pts", "Home", "Road", "Div rec", "Conf rec", "Strk", "L5", "Source"],
    rows,
    note="32 teams · transcribed from the NFL.com league standings table (2026 regular season, through Week 9) · league order follows the source page (sorted by win percentage) · source retrieved Nov 14, 2026")
standings_note = (
    '<section class="card"><h2>Verification notes</h2><p>Consistency checks re-run on every build by '
    '<code>scripts/build_data.py</code>: points-for minus points-against equals net points, and home plus road '
    'record equals games played, for all 32 teams. The source table contains one unnamed extra column after '
    'the conference record; it was <b>omitted</b> from this page rather than guessed (review note F60-1, '
    'recorded in COORDINATION.md).</p></section>'
)
(ROOT / "data-standings.html").write_text(page(
    "Data · Standings (through Week 9)", "Data snapshots", "VERIFIED SNAPSHOT · OFFICIAL NFL.COM",
    "Standings — 2026 season, through Week 9",
    "All 32 team records, points, and splits transcribed from the official NFL league standings page.",
    standings_body + standings_note, "data-standings"), encoding="utf-8")

# ----------------------------------------------------------------- schedule --
sc = read_csv("schedule_2026_wk10.csv")
rows = []
for r in sc:
    src = f'<a class="src" href="{esc(r["game_url"])}" target="_blank" rel="noopener">NFL.com game page</a>'
    ap = esc(r["away_pts"]) if r["away_pts"] else ""
    hp = esc(r["home_pts"]) if r["home_pts"] else ""
    rows.append(
        "<tr><td>{d}</td><td>{t}</td><td>{s}</td><td>{a}</td><td>{h}</td><td>{n}</td><td>{v}</td><td>{st}</td><td>{ap}</td><td>{hp}</td><td>{src}</td></tr>".format(
            d=esc(r["date"]), t=esc(r["time_et"]), s=esc(r["slot"]), a=esc(r["away"]), h=esc(r["home"]),
            n=esc(r["network"]), v=esc(r["venue_note"]), st=esc(r["status"]), ap=ap, hp=hp, src=src))
bye = read_csv("bye_teams_2026_wk10.csv")
bye_rows = ["<tr><td>{t}</td><td>{r}</td><td>{s}</td></tr>".format(
    t=esc(b["team"]), r=esc(b["record"]),
    s=f'<a class="src" href="{esc(b["source_url"])}" target="_blank" rel="noopener">NFL.com schedule</a>') for b in bye]
schedule_body = (
    table(["Date", "Kickoff (ET)", "Slot", "Away", "Home", "Network", "Venue note", "Status", "Away pts", "Home pts", "Source"],
          rows, note="14 games · transcribed from the official NFL.com Week 10 schedule · source retrieved Nov 14, 2026 (TNF already final)")
    + table(["Team", "Record", "Source"], bye_rows, searchable=False,
            note="Teams on bye, as listed on the official Week 10 schedule page")
)
(ROOT / "data-schedule.html").write_text(page(
    "Data · Week 10 schedule", "Data snapshots", "VERIFIED SNAPSHOT · OFFICIAL NFL.COM",
    "Week 10 schedule — 2026 season",
    "Kickoff slots, networks, results-to-date, and the four teams on bye, transcribed from the official NFL schedule page.",
    schedule_body, "data-schedule"), encoding="utf-8")

# ----------------------------------------------------------------- injuries --
inj = read_csv("injuries_2026_wk10.csv")
rows = []
for r in inj:
    src = f'<a class="src" href="{esc(r["source_url"])}" target="_blank" rel="noopener">NFL.com injury report</a>'
    inj_field = esc(r["injuries"]) if r["injuries"] else ""
    note = esc(r["note"]) if r["note"] and r["note"] != "Transcribed from NFL.com league injury report (final Week 10 report)" else ""
    rows.append(
        "<tr><td>{tm}</td><td>{op}</td><td>{d}</td><td>{p}</td><td>{po}</td><td>{i}</td><td>{pr}</td><td>{gs}</td><td>{src}</td><td>{no}</td></tr>".format(
            tm=esc(r["team"]), op=esc(r["opponent"]), d=esc(r["game_date"]), p=esc(r["player"]), po=esc(r["position"]),
            i=inj_field, pr=esc(r["practice_status"]), gs=esc(r["game_status"]), src=src, no=note))
OFF = {"QB", "RB", "FB", "WR", "TE", "T", "G", "C"}
DEF = {"DT", "DE", "DL", "LB", "CB", "S", "DB"}
teams = {}
for r in inj:
    t = teams.setdefault(r["team"], {"opp": r["opponent"], "out": 0, "doubtful": 0, "quest": 0, "off": 0, "def": 0})
    gs = r["game_status"]
    if gs in ("Out", "Doubtful"):
        t["out" if gs == "Out" else "doubtful"] += 1
        if r["position"] in OFF:
            t["off"] += 1
        if r["position"] in DEF:
            t["def"] += 1
    elif gs == "Questionable":
        t["quest"] += 1
order = []
for r in sc:
    order.append(r["away"]); order.append(r["home"])
def_rows = []
for tm in order:
    t = teams.get(tm)
    if not t:
        continue
    def_rows.append(
        "<tr><td>{tm}</td><td>{op}</td><td>{o}</td><td>{df}</td><td>{q}</td><td>{of}</td><td>{de}</td><td>{s}</td></tr>".format(
            tm=esc(tm), op=esc(t["opp"]), o=t["out"], df=t["doubtful"], q=t["quest"], of=t["off"], de=t["def"],
            s='<a class="src" href="https://www.nfl.com/injuries/league/2026/reg10" target="_blank" rel="noopener">NFL.com injury report</a>'))
news = read_csv("injury_news_2026_wk10.csv")
news_rows = ["<tr><td>{h}</td><td>{s}</td></tr>".format(
    h=esc(n["headline"]),
    s=f'<a class="src" href="{esc(n["url"])}" target="_blank" rel="noopener">NFL.com news</a>') for n in news]
injuries_body = (
    table(["Team", "Opp", "Game date", "Player", "Pos", "Injuries", "Practice status", "Game status", "Source", "Note"],
          rows, note="345 player rows · 28 teams (CHI, DEN, PHI, TB on bye) · transcribed from the official NFL.com league injury report for Week 10 (final Friday report) · source retrieved Nov 14, 2026")
    + '<section class="card"><h2>Team deficiency snapshot (derived)</h2>'
      '<div class="filter-row"><span class="small-note">Counts computed mechanically from the verified table above · "key absences" = Out/Doubtful by unit · position→unit mapping (offense: QB RB FB WR TE T G C · defense: DT DE DL LB CB S DB) is documented in docs/injury-depth-deficiency.md · depth-string (2nd/3rd/4th) claims remain blank pending verified depth charts — see the depth section of this site (depth/)</span></div>'
      '<div class="table-wrap"><table class="data-table"><thead><tr><th>Team</th><th>Opp</th><th>Out</th><th>Doubtful</th><th>Questionable</th><th>Key offensive absences</th><th>Key defensive absences</th><th>Source</th></tr></thead><tbody>'
      + "\n".join(def_rows) + "</tbody></table></div></section>"
    + table(["Headline (official NFL.com news)", "Source"], news_rows, searchable=False,
            note="Headlines transcribed from the news section of the official Week 10 injury report page · note the two Lamar Jackson timelines differ (review note F60-4)")
)
(ROOT / "data-injuries.html").write_text(page(
    "Data · Week 10 injury report", "Data snapshots", "VERIFIED SNAPSHOT · OFFICIAL NFL.COM",
    "Week 10 injury report — 2026 season",
    "The final Friday league injury report for every Week 10 team, transcribed player-by-player from the official NFL.com league report.",
    injuries_body, "data-injuries"), encoding="utf-8")

# --------------------------------------------------------------------- hub --
cards = [
    ("Standings — through Week 9", "32 teams: records, points for/against, splits, streaks. Consistency-checked on every build.", "data-standings.html"),
    ("Week 10 schedule", "14 games + 4 byes: kickoff slots, networks, official game-page links, TNF final score.", "data-schedule.html"),
    ("Week 10 injury report", "345 player rows across 28 teams: injury, practice status, game status, plus derived team deficiency counts.", "data-injuries.html"),
    ("Machine-readable datasets", "The same values as CSV/JSON under <code>data/</code> in the repository, generated by <code>scripts/build_data.py</code> with consistency assertions.", "https://github.com/sassnarep3-star/FL3"),
]
cards_html = "".join(
    f'<a class="tile" href="{href}"><h3>{t}</h3><p>{d}</p><span class="card-link">Open →</span></a>'
    for t, d, href in cards)
hub_body = f'<section class="card"><h2>Snapshot library</h2><div class="grid">{cards_html}</div></section>' + (
    '<section class="card"><h2>Related registers</h2><p>Suggestion register: <code>docs/suggestions.md</code> and the live '
    '<a href="suggestions.html">Suggestions</a> page · decision questions: <a href="decisions.html">Decisions</a> · '
    'methodology: <a href="methodology.html">Methodology</a> · open irregularities: <a href="flagged.html">Flagged for Review</a>. '
    'The depth/backup section of this site lives under <b>depth/</b> (separate dashboard).</p></section>')
(ROOT / "data-snapshots.html").write_text(page(
    "Data snapshots", "Data snapshots", "VERIFIED SNAPSHOT · OFFICIAL NFL.COM",
    "Data snapshots",
    "Point-in-time transcriptions of official NFL.com pages (retrieved November 14, 2026), with the official source linked on every row.",
    hub_body, "data"), encoding="utf-8")

print("root data pages written:", ["data-snapshots.html", "data-standings.html", "data-schedule.html", "data-injuries.html"])
